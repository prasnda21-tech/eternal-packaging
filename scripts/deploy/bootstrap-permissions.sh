#!/usr/bin/env bash
# Least-privilege bootstrap for deploy user directories + systemd restart sudoers.
# Default is dry-run. Pass --apply to write (Owner/root on VPS only).
#
# Creates a dedicated runtime root under /opt (leaf only) — NEVER chown/chmod
# /opt or /var/www parents. Webroot must already be writable by deploy user
# (or created as the leaf path with install -d).
#
# Does NOT grant NOPASSWD:ALL.
# Does NOT mutate /opt/eternal-packaging dirty tree contents.
# Does NOT grant sudo to user-writable scripts or arbitrary shell.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

APPLY=0
# VPS evidence: service user is eternaladmin (override via env).
DEPLOY_USER="${ETERNAL_BOOTSTRAP_DEPLOY_USER:-eternaladmin}"
RUNTIME_ROOT="${ETERNAL_RUNTIME_ROOT:-/opt/eternal-packaging-runtime}"
RELEASES_ROOT="${ETERNAL_RELEASES_ROOT:-$RUNTIME_ROOT/releases}"
CURRENT_LINK="${ETERNAL_CURRENT_LINK:-$RUNTIME_ROOT/current}"
FRONTEND_ROOT="${ETERNAL_FRONTEND_ROOT:-/var/www/eternal-packaging}"
FRONTEND_PREV="${ETERNAL_FRONTEND_PREV:-$RUNTIME_ROOT/frontend-prev}"
SERVICE_NAME="${ETERNAL_SERVICE_NAME:-eternal-packaging-backend.service}"
SUDOERS_PATH="${ETERNAL_SUDOERS_PATH:-/etc/sudoers.d/eternal-packaging-deploy}"
WWW_GROUP="${ETERNAL_WWW_GROUP:-www-data}"
SYSTEMCTL_PATH="${ETERNAL_SYSTEMCTL_PATH:-/bin/systemctl}"

for arg in "$@"; do
  case "$arg" in
    --apply) APPLY=1 ;;
    --help|-h)
      cat <<EOF
Usage: bootstrap-permissions.sh [--apply]
  Dry-run by default. Prints planned mkdir/chown/sudoers.
  --apply requires root and writes changes.
  Never modifies ownership of /opt or /var/www themselves.
EOF
      exit 0
      ;;
    *) eternal_deploy_die "unknown arg: $arg" ;;
  esac
done

eternal_validate_bootstrap_inputs() {
  [[ "$DEPLOY_USER" =~ ^[a-z_][a-z0-9_-]*$ ]] || eternal_deploy_die "invalid deploy user: $DEPLOY_USER"
  [[ "$SERVICE_NAME" =~ ^[a-zA-Z0-9_.@-]+\.service$ ]] || eternal_deploy_die "invalid service name"
  [[ "$SYSTEMCTL_PATH" == /bin/systemctl || "$SYSTEMCTL_PATH" == /usr/bin/systemctl ]] \
    || eternal_deploy_die "systemctl path must be /bin/systemctl or /usr/bin/systemctl"
  [[ "$SUDOERS_PATH" == /etc/sudoers.d/eternal-packaging-deploy ]] \
    || eternal_deploy_die "sudoers path must be fixed /etc/sudoers.d/eternal-packaging-deploy"
  # Fixed allowlisted absolute paths only.
  local p
  for p in "$RUNTIME_ROOT" "$RELEASES_ROOT" "$CURRENT_LINK" "$FRONTEND_PREV" "$FRONTEND_ROOT"; do
    [[ "$p" == /* ]] || eternal_deploy_die "path must be absolute: $p"
    [[ "$p" != "/" && "$p" != "/opt" && "$p" != "/var" && "$p" != "/var/www" ]] \
      || eternal_deploy_die "refusing to operate on parent path: $p"
  done
  case "$RUNTIME_ROOT" in
    /opt/eternal-packaging-runtime) ;;
    *) eternal_deploy_die "runtime root must be /opt/eternal-packaging-runtime (got $RUNTIME_ROOT)" ;;
  esac
  case "$RELEASES_ROOT" in
    "$RUNTIME_ROOT"/releases) ;;
    *) eternal_deploy_die "releases root must be \$RUNTIME_ROOT/releases" ;;
  esac
  case "$CURRENT_LINK" in
    "$RUNTIME_ROOT"/current) ;;
    *) eternal_deploy_die "current link must be \$RUNTIME_ROOT/current" ;;
  esac
  case "$FRONTEND_PREV" in
    "$RUNTIME_ROOT"/frontend-prev) ;;
    *) eternal_deploy_die "frontend-prev must be under runtime root (not /var/www sibling)" ;;
  esac
  case "$FRONTEND_ROOT" in
    /var/www/eternal-packaging) ;;
    *) eternal_deploy_die "frontend root must be /var/www/eternal-packaging" ;;
  esac
}

sudoers_body=$(cat <<EOF
# Eternal Packaging deploy — least privilege (generated by bootstrap-permissions.sh)
# Allows ONLY restart/status/show of the backend unit. No shell. No unrestricted sudo.
# Does NOT allow running user-writable scripts as root.
Cmnd_Alias ETERNAL_PACKAGING_SYSTEMCTL = \\
  ${SYSTEMCTL_PATH} restart ${SERVICE_NAME}, \\
  ${SYSTEMCTL_PATH} is-active ${SERVICE_NAME}, \\
  ${SYSTEMCTL_PATH} show ${SERVICE_NAME}

${DEPLOY_USER} ALL=(root) NOPASSWD: ETERNAL_PACKAGING_SYSTEMCTL
EOF
)

plan() {
  cat <<EOF
PLAN bootstrap least-privilege
  deploy_user=$DEPLOY_USER
  runtime_root=$RUNTIME_ROOT (create leaf; owner $DEPLOY_USER; NEVER chown /opt)
  releases_root=$RELEASES_ROOT (mode 755, owner $DEPLOY_USER)
  current_link=$CURRENT_LINK (symlink replaceable by $DEPLOY_USER inside runtime root)
  frontend_prev=$FRONTEND_PREV (FE backup under runtime root; not /var/www sibling)
  frontend_root=$FRONTEND_ROOT (must already be writable by $DEPLOY_USER; NEVER chown /var/www)
  sudoers=$SUDOERS_PATH
  note=EnvironmentFiles stay on legacy paths (/opt/eternal-packaging/backend/.env, /etc/eternal-packaging-google-places.env)
--- sudoers ---
$sudoers_body
--- end sudoers ---
EOF
}

apply_changes() {
  [[ "$(id -u)" == "0" ]] || eternal_deploy_die "--apply requires root"
  eternal_validate_bootstrap_inputs
  id "$DEPLOY_USER" >/dev/null 2>&1 || eternal_deploy_die "deploy user missing: $DEPLOY_USER"

  # Create dedicated leaf under /opt without changing /opt ownership/mode.
  install -d -m 755 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$RUNTIME_ROOT"
  install -d -m 755 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$RELEASES_ROOT"
  install -d -m 755 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$RELEASES_ROOT/backups"
  install -d -m 755 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$FRONTEND_PREV"

  if [[ -e "$CURRENT_LINK" && ! -L "$CURRENT_LINK" ]]; then
    eternal_deploy_die "$CURRENT_LINK exists and is not a symlink; refuse to clobber"
  fi
  if [[ -L "$CURRENT_LINK" ]]; then
    chown -h "$DEPLOY_USER:$DEPLOY_USER" "$CURRENT_LINK" || true
  fi

  # Webroot: create leaf only if missing. Never chown /var/www.
  if [[ ! -e "$FRONTEND_ROOT" ]]; then
    install -d -m 755 -o "$DEPLOY_USER" -g "$WWW_GROUP" "$FRONTEND_ROOT"
  else
    [[ -d "$FRONTEND_ROOT" ]] || eternal_deploy_die "frontend root exists but is not a directory"
    # Verify deploy user can write without altering parent ownership.
    if ! sudo -u "$DEPLOY_USER" test -w "$FRONTEND_ROOT"; then
      eternal_deploy_die "frontend root $FRONTEND_ROOT not writable by $DEPLOY_USER; fix ownership of the leaf only (never chown /var/www)"
    fi
  fi

  # Prove we did not alter parent modes/owners as part of this helper contract.
  local opt_owner www_owner
  opt_owner="$(stat -c '%U:%G' /opt)"
  www_owner="$(stat -c '%U:%G' /var/www)"
  eternal_deploy_log "parent ownership unchanged check: /opt=$opt_owner /var/www=$www_owner"

  printf '%s\n' "$sudoers_body" >"$SUDOERS_PATH"
  chmod 440 "$SUDOERS_PATH"
  if command -v visudo >/dev/null 2>&1; then
    visudo -cf "$SUDOERS_PATH" || eternal_deploy_die "sudoers validation failed"
  fi
  eternal_deploy_log "bootstrap APPLY complete runtime_root=$RUNTIME_ROOT"
}

eternal_validate_bootstrap_inputs
plan
if [[ "$APPLY" == "1" ]]; then
  apply_changes
else
  eternal_deploy_log "dry-run only (pass --apply to write)"
fi
