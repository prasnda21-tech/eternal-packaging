#!/usr/bin/env bash
# Mint a SHA-scoped migration approval manifest for the deploy gate.
# Does not execute migrations. Owner-operated only.
#
# Usage:
#   ./mint-migration-approval.sh --target-sha <40hex> --git-dir <mirror.git> \
#       --out migration-approvals/name.v1 --path P --path P ...
#   ./mint-migration-approval.sh --target-sha <40hex> --work-tree <repo> \
#       --from-sha <prev> --out ...
#       (auto-collect blocked paths in from..target)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

TARGET_SHA=""
FROM_SHA=""
GIT_DIR=""
WORK_TREE=""
OUT=""
PATHS=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --target-sha) TARGET_SHA="${2:-}"; shift 2 ;;
    --from-sha) FROM_SHA="${2:-}"; shift 2 ;;
    --git-dir) GIT_DIR="${2:-}"; shift 2 ;;
    --work-tree) WORK_TREE="${2:-}"; shift 2 ;;
    --out) OUT="${2:-}"; shift 2 ;;
    --path) PATHS+=("${2:-}"); shift 2 ;;
    *) eternal_deploy_die "unknown arg: $1" ;;
  esac
done

eternal_require_sha40 "$TARGET_SHA"
[[ -n "$OUT" ]] || eternal_deploy_die "--out required"
[[ -n "$GIT_DIR" || -n "$WORK_TREE" ]] || eternal_deploy_die "git-dir or work-tree required"

if ((${#PATHS[@]} == 0)); then
  [[ -n "$FROM_SHA" ]] || eternal_deploy_die "--path or --from-sha required"
  eternal_require_sha40 "$FROM_SHA"
  local_blocked=""
  if ! local_blocked="$(eternal_collect_blocked_migrations "$FROM_SHA" "$TARGET_SHA" "$GIT_DIR" "$WORK_TREE")"; then
    eternal_deploy_die "no blocked migration paths in range; nothing to approve"
  fi
  while IFS= read -r line; do
    [[ -z "$line" ]] && continue
    PATHS+=("$line")
  done <<<"$local_blocked"
fi

{
  printf '%s\n' "# Generated by mint-migration-approval.sh — does NOT execute migrations."
  printf '%s\n' "schema=eternal.deploy.migration_approval.v1"
  printf 'target_sha=%s\n' "$TARGET_SHA"
  # Sort paths for stable manifests.
  while IFS= read -r p; do
    [[ -z "$p" ]] && continue
    blob="$(eternal_git_blob_at "$TARGET_SHA" "$p" "$GIT_DIR" "$WORK_TREE")" \
      || eternal_deploy_die "missing blob for $p at $TARGET_SHA"
    printf 'path=%s\n' "$p"
    printf 'blob=%s\n' "$blob"
  done < <(printf '%s\n' "${PATHS[@]}" | LC_ALL=C sort -u)
} >"$OUT"
chmod 644 "$OUT"
eternal_deploy_log "wrote approval $OUT target_sha=$TARGET_SHA paths=${#PATHS[@]}"
printf 'MINT_OK path=%s\n' "$OUT"
